module OpenAPISchemas
  def self.object(properties, optional: [], **options)
    { type: :object, required: (properties.keys - optional).map(&:to_s), properties:, **options }
  end

  def self.ref(name) = { "$ref" => "#/components/schemas/#{name}" }

  def self.nullable(name) = { oneOf: [ ref(name), { type: "null" } ] }

  SERIAL_NUMBER = { type: :string, pattern: "^[0-9]{6}$", example: "000001", description: "Six digits, leading zeros included. Never reused." }.freeze
  CARD_NUMBER = { type: :string, pattern: "^[0-9]{6}$", example: "100001", description: "Six digits, leading zeros included." }.freeze
  PLAIN_TEXT = { type: :string, minLength: 1, maxLength: 255, description: "Trimmed, with at least one visible character and no control characters." }.freeze
  TIMESTAMP = { type: :string, format: "date-time", description: "UTC, RFC 3339 with milliseconds." }.freeze
  NULLABLE_TIMESTAMP = TIMESTAMP.merge(type: [ :string, "null" ]).freeze
  UUID = { type: :string, format: :uuid, description: "UUIDv7 generated by PostgreSQL." }.freeze
  FULL_NAME = PLAIN_TEXT.merge(example: "Ada Lovelace").freeze
  BOOK = { serial_number: SERIAL_NUMBER, title: PLAIN_TEXT.merge(example: "Dune"), author: PLAIN_TEXT.merge(example: "Frank Herbert") }.freeze
  BOOK_STATE = {
    status: { type: :string, enum: Book::STATUSES, description: "Derived: withdrawn, else borrowed while a borrowing is open, else available." },
    withdrawn_at: NULLABLE_TIMESTAMP.merge(description: "When the book left the catalog; null while it is in the catalog."),
    current_borrowing: nullable(:BookBorrowing)
  }.freeze
  BOOK_BORROWING = {
    id: UUID,
    reader: ref(:Reader),
    borrowed_at: TIMESTAMP,
    due_on: { type: :string, format: :date, description: "Calendar date in Europe/Warsaw, 30 days after the borrow." },
    returned_at: NULLABLE_TIMESTAMP.merge(description: "Null until the book is returned.")
  }.freeze

  ALL = {
    NewBook: object(BOOK),
    Book: object(BOOK.merge(BOOK_STATE)),
    BookDetail: object(BOOK.merge(BOOK_STATE).merge(
      borrowings: { type: :array, items: ref(:BookBorrowing), description: "Full borrowing history, newest first." }
    )),
    NewBorrowing: object({ card_number: CARD_NUMBER }),
    BookBorrowing: object(BOOK_BORROWING, description: "A borrowing as listed under its book."),
    Borrowing: object(BOOK_BORROWING.merge(book: ref(:BookSummary))),
    Reader: object({
      card_number: CARD_NUMBER,
      full_name: FULL_NAME,
      email: { type: :string, format: :email, maxLength: 254, example: "ada@example.com", description: "Stored trimmed and lower-cased; unique." }
    }),
    BookSummary: object(BOOK.slice(:serial_number, :title)),
    Problem: object({
      type: { type: :string, format: :"uri-reference", example: "/problems#book-borrowed",
              description: "`about:blank` for plain HTTP errors, otherwise a stable reference documented at `/problems`." },
      title: { type: :string },
      status: { type: :integer },
      detail: { type: :string },
      instance: { type: :string, format: :"uri-reference", description: "The request path." },
      request_id: { type: :string, description: "Same as the `X-Request-Id` response header." },
      errors: {
        type: :array,
        description: "Present when attributes are invalid.",
        items: object({ pointer: { type: :string, example: "#/title" }, detail: { type: :string, example: "can't be blank" } })
      }
    }, optional: %i[ detail instance request_id errors ]),
    Liveness: object({ status: { type: :string, enum: %w[ ok ] } }),
    Readiness: object({
      status: { type: :string, enum: %w[ ok unavailable ] },
      uptime: { type: :number, description: "Seconds since the process booted." },
      checks: object({ database: { type: :string, enum: %w[ ok error ] } })
    })
  }.freeze
end
